"""Render the MERRY chat for the root app's "Ask MERRY" tab.

    python3 merry_agent/tools/build_tab.py --db MERRY

Writes merry_agent/app/* (rendered for one database: {{DB}} replaced) into <workspace root>/merry_chat/. The root app
imports merry_chat/merry_tab.py. merry_agent/app/ stays the only source: never edit merry_chat/ by hand."""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))
import settings  # noqa: E402
SRC = os.path.join(os.path.dirname(HERE), "app")
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "merry_chat")
FILES = ["merry_tab.py", "review.py", "chat.py", "common.py", "onboard.py", "lib/merry_sql.py"]

ap = argparse.ArgumentParser()
ap.add_argument("--db", default=settings.DB)
db = ap.parse_args().db.upper()
assert re.fullmatch(r"[A-Z][A-Z0-9_]{0,200}", db), f"bad database name {db}"
os.makedirs(os.path.join(OUT, "lib"), exist_ok=True)       # overwrite in place: the workspace mount is a stage
open(os.path.join(OUT, "lib", "__init__.py"), "w").close()
for rel in FILES:
    txt = settings.render(open(os.path.join(SRC, rel)).read(), db)
    open(os.path.join(OUT, rel), "w").write(f"# Generated by merry_agent/tools/build_tab.py for {db}. Do not edit.\n" + txt)
    print(f"  wrote merry_chat/{rel}")
