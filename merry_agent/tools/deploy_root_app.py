"""Deploy the MERRY app: the Streamlit app at the repository root (Dashboard, Issues, Ask MERRY, Data) on the container
runtime. Usually run through setup.py.

    python3 merry_agent/tools/deploy_root_app.py [--db NAME]

Builds merry_chat/ (build_tab.py), writes snowflake.yml from settings.py, uploads the app files to
<DB>.APP.ROOT_APP_STAGE, then creates <DB>.APP.MERRY (first run) or updates it in place: its settings are set again,
the files are copied into its live version and committed as a new version. The app is never dropped or re-created, so
its URL, grants and open sessions keep pointing at the same app. The stage is created if missing and files are
overwritten, never removed."""
import argparse, os, subprocess, sys, snowflake.connector

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
import settings  # noqa: E402

FILES = ["pyproject.toml", "streamlit_app.py", "dashboard.py", "audit_rules.py", "ingest.py"]            # plus everything in merry_chat/

ap = argparse.ArgumentParser()
ap.add_argument("--db", default=settings.DB)
db = ap.parse_args().db.upper()
v = settings.values(db)
role, wh, pool = v["{{ROLE}}"], v["{{WAREHOUSE}}"], v["{{COMPUTE_POOL}}"]
app, stage = f"{db}.APP.{settings.APP_NAME}", f"{db}.APP.ROOT_APP_STAGE"

subprocess.run([sys.executable, os.path.join(HERE, "build_tab.py"), "--db", db], check=True)
open(os.path.join(ROOT, "snowflake.yml"), "w").write(f"""# Generated by merry_agent/tools/deploy_root_app.py from settings.py. Do not edit; change settings.py.
definition_version: 2
entities:
  streamlit_app:
    type: streamlit
    identifier: {app}
    main_file: streamlit_app.py
    title: "MERRY"
    query_warehouse: "{wh}"
    compute_pool: "{pool}"
    artifacts:
""" + "".join(f"      - {f}\n" for f in FILES + ["merry_chat/"]))

files = list(FILES)
for d, _, fs in os.walk(os.path.join(ROOT, "merry_chat")):
    if "__pycache__" not in d:
        files += [os.path.relpath(os.path.join(d, f), ROOT) for f in fs if f.endswith(".py")]
k = snowflake.connector.connect(connection_name=settings.CONNECTION).cursor()
for s in (f"USE ROLE {role}", "USE SECONDARY ROLES NONE", f"USE WAREHOUSE {wh}",
          f"CREATE STAGE IF NOT EXISTS {stage} ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')"):
    k.execute(s)
for rel in sorted(files):
    k.execute(f"PUT 'file://{os.path.join(ROOT, rel)}' @{stage}/{os.path.dirname(rel)} AUTO_COMPRESS = FALSE OVERWRITE = TRUE")
    print(f"  put {rel}")
props = f"""MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = {wh}
  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'
  COMPUTE_POOL = {pool}
  TITLE = 'MERRY'"""
k.execute(f"SHOW STREAMLITS LIKE '{settings.APP_NAME}' IN SCHEMA {db}.APP")
if not k.fetchall():
    k.execute(f"CREATE STREAMLIT {app}\n  FROM '@{stage}'\n  {props}")
    k.execute(f"ALTER STREAMLIT {app} ADD LIVE VERSION FROM LAST")
    print(f"== app {app} created, owned by {role} (Snowsight > Projects > Streamlit > MERRY)")
else:
    # Update in place: same object, URL and grants; the files become a new committed version of the live app.
    k.execute(f"ALTER STREAMLIT {app} SET {props}")
    k.execute(f"DESCRIBE STREAMLIT {app}")
    d = dict(zip([c[0] for c in k.description], k.fetchone()))
    if not d.get("live_version_location_uri"):
        k.execute(f"ALTER STREAMLIT {app} ADD LIVE VERSION FROM LAST")
    live = f"snow://streamlit/{app}/versions/live/"
    k.execute(f"COPY FILES INTO '{live}' FROM @{stage}/")
    k.execute(f"ALTER STREAMLIT {app} COMMIT")
    k.execute(f"DESCRIBE STREAMLIT {app}")
    d = dict(zip([c[0] for c in k.description], k.fetchone()))
    print(f"== app {app} updated in place to {d.get('last_version_name')}, owned by {role}")
